        particleSpeed = particleSpeed.coerceIn(0f, 10f),
        particleSize = particleSize.coerceIn(0f, 64f),
        particleSpread = particleSpread.coerceIn(0f, 10f),
        particleSpreadY = particleSpreadY.coerceIn(0f, 10f),
        measureAmount = measureAmount.coerceIn(0f, 1f),
        trackPositionFraction = trackPositionFraction.coerceIn(0f, 1f),
