package com.auralis.app.visualizer

data class VisualizerSettings(
    val barCount: Int = 64,
    val sensitivity: Float = 1f,
    val smoothing: Float = 0.35f,
    val glow: Float = 0.25f,
    val opacity: Float = 1f,
    val mirror: Boolean = false,
    val positionX: Float = 0.5f,
    val positionY: Float = 0.5f,
    val scale: Float = 1f,
    val rotation: Float = 0f,
    val particlesEnabled: Boolean = false,
    val barsEnabled: Boolean = true,
    val particleCount: Int = 120,
    val particleSpeed: Float = 1f,
    val particleSize: Float = 3f,
    val particleSpread: Float = 0.8f,
    val particleMirrorX: Boolean = false,
    val particleMirrorY: Boolean = false,
    val positionMeasure: MeasureWhat = MeasureWhat.NOTHING,
    val scaleMeasure: MeasureWhat = MeasureWhat.NOTHING,
    val rotationMeasure: MeasureWhat = MeasureWhat.NOTHING,
    val measureAmount: Float = 0.5f,
    val trackPositionFraction: Float = 0f,
    val beatSensitivity: Float = 0.55f,
    val particleOpacity: Float = 1f,
    val particlePositionX: Float = 0.5f,
    val particlePositionY: Float = 0.5f,
    val particleScale: Float = 1f,
    val particleRotation: Float = 0f,
    val particlePositionMeasure: MeasureWhat = MeasureWhat.NOTHING,
    val particleScaleMeasure: MeasureWhat = MeasureWhat.NOTHING,
    val particleRotationMeasure: MeasureWhat = MeasureWhat.NOTHING,
    val particleMeasureAmount: Float = 0.5f,
    val rgbSplitAmount: Float = 0f,
    val barWidth: Float = 0.72f,
    val barHeight: Float = 1f,
    val barMinHeight: Float = 0f,
    val flipInput: Boolean = false,
    val barColorFrom: Long = 0xFFFFFFFF,
    val barColorTo: Long = 0xFF00FFFF,
    val particleColor: Long = 0xFFFFFFFF,
    val segmentCount: Int = 1,
    val segmentGap: Float = 0.18f
) {
    fun sanitized() = copy(
        barCount = barCount.coerceIn(16, 128),
        sensitivity = sensitivity.coerceIn(0.1f, 4f),
        smoothing = smoothing.coerceIn(0f, 0.95f),
        glow = glow.coerceIn(0f, 1f),
        opacity = opacity.coerceIn(0f, 1f),
        positionX = positionX.coerceIn(-1f, 2f),
        positionY = positionY.coerceIn(-1f, 2f),
        scale = scale.coerceIn(0.1f, 3f),
        rotation = rotation.coerceIn(-180f, 180f),
        particleCount = particleCount.coerceIn(0, 400),
        particleSpeed = particleSpeed.coerceIn(0.1f, 4f),
        particleSize = particleSize.coerceIn(1f, 12f),
        particleSpread = particleSpread.coerceIn(0.1f, 2f),
        measureAmount = measureAmount.coerceIn(0f, 1f),
        trackPositionFraction = trackPositionFraction.coerceIn(0f, 1f),
        beatSensitivity = beatSensitivity.coerceIn(0f, 1f),
        particleOpacity = particleOpacity.coerceIn(0f, 1f),
        particlePositionX = particlePositionX.coerceIn(-1f, 2f),
        particlePositionY = particlePositionY.coerceIn(-1f, 2f),
        particleScale = particleScale.coerceIn(0.1f, 3f),
        particleRotation = particleRotation.coerceIn(-180f, 180f),
        particleMeasureAmount = particleMeasureAmount.coerceIn(0f, 1f),
        rgbSplitAmount = rgbSplitAmount.coerceIn(0f, 1f),
        barWidth = barWidth.coerceIn(0.15f, 1f),
        barHeight = barHeight.coerceIn(0.1f, 2f),
        barMinHeight = barMinHeight.coerceIn(0f, 1f),
        segmentCount = segmentCount.coerceIn(1, 32),
        segmentGap = segmentGap.coerceIn(0f, 0.45f)
    )
}
