        particlePositionX = particlePositionX.coerceIn(-1f, 2f),
        particlePositionY = particlePositionY.coerceIn(-1f, 2f),
        particleScale = particleScale.coerceIn(0.1f, 4f),
        particleRotation = particleRotation.coerceIn(0f, 360f),
        particleVectorAngle = particleVectorAngle.coerceIn(0f, 360f),
        particleVectorAngleZ = particleVectorAngleZ.coerceIn(0f, 360f),
